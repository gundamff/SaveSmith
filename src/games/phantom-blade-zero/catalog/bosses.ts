function readableBossId(bossId: string): string {
  return bossId.replace(/^BP_Monster_/, '').replace(/_/g, ' ')
}

export function getBossDisplayName(bossId: string, locale: BossLocale): string {
  const hit = BOSS_NAMES[bossId]
  if (!hit) return readableBossId(bossId)
  if (locale === 'zh') return hit.zh
  return hit.en || readableBossId(bossId)
}

export function listBossCatalogIds(): string[] {
  return Object.keys(BOSS_NAMES)
}
