/**
 * One-shot converter: public community derived JSON → SaveSmith catalog files.
 *
 * Source (facts only, not editor business logic):
 * https://github.com/gfriloux/dragonsword-save-editor/tree/main/internal/domain/data
 *
 * Run: node scripts/convert-dragon-sword-catalog.mjs
 * Expects tmp-catalog/{items,recipes,titles}.json already downloaded.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const srcDir = path.join(root, 'tmp-catalog')
const outDir = path.join(root, 'src', 'games', 'dragon-sword', 'catalog')

function readJson(name) {
  return JSON.parse(fs.readFileSync(path.join(srcDir, name), 'utf8'))
}

function localized(en, fr) {
  const e = (en || fr || '').trim()
  const f = (fr || en || '').trim()
  // Public tables are FR/EN only; zh falls back to EN until a local StringData export exists.
  return { zh: e || f, en: e || f }
}

function writeJson(name, value) {
  const text = `${JSON.stringify(value, null, 2)}\n`
  fs.writeFileSync(path.join(outDir, name), text, 'utf8')
  console.log(`wrote ${name} (${Array.isArray(value) ? value.length : Object.keys(value).length})`)
}

const itemsFile = readJson('items.json')
const recipesFile = readJson('recipes.json')
const titlesFile = readJson('titles.json')

const labels = {}
const characters = []
const currencies = []

for (const [cidStr, row] of Object.entries(itemsFile.items || {})) {
  const cid = Number(cidStr)
  if (!Number.isFinite(cid)) continue
  const name = localized(row.en, row.fr)
  if (!name.en && !name.zh) continue
  labels[cidStr] = name

  const category = row.category || ''
  const type = row.type || ''
  if (category === 'character' || type === 'CHARACTER') {
    characters.push({ characterCid: cid, name })
  }
  if (category === 'currency') {
    currencies.push({ itemCid: cid, name })
  }
}

characters.sort((a, b) => a.characterCid - b.characterCid)
currencies.sort((a, b) => a.itemCid - b.itemCid)

const recipes = []
const seenSwitch = new Set()
for (const row of recipesFile.recipes || []) {
  const switchKey = Number(row.key)
  if (!Number.isFinite(switchKey) || seenSwitch.has(switchKey)) continue
  seenSwitch.add(switchKey)
  const dishCid = Array.isArray(row.dishes) ? Number(row.dishes[0]) : undefined
  let name = localized(row.effectName?.en, row.effectName?.fr)
  if (dishCid && labels[String(dishCid)]) {
    name = labels[String(dishCid)]
  }
  recipes.push({
    switchKey,
    ...(Number.isFinite(dishCid) ? { dishCid } : {}),
    name
  })
}
recipes.sort((a, b) => a.switchKey - b.switchKey)

const titles = []
for (const row of Object.values(titlesFile.titles || {})) {
  const titleId = Number(row.id)
  if (!Number.isFinite(titleId)) continue
  titles.push({
    titleId,
    name: localized(row.nameEn, row.nameFr)
  })
}
titles.sort((a, b) => a.titleId - b.titleId)

writeJson('labels.json', labels)
writeJson('characters.json', characters)
writeJson('currencies.json', currencies)
writeJson('recipes.json', recipes)
writeJson('titles.json', titles)

fs.writeFileSync(
  path.join(outDir, 'SOURCE.md'),
  [
    '# DragonSword catalog provenance',
    '',
    'Derived CID → name tables converted from the public Apache-2.0 data files in',
    '[gfriloux/dragonsword-save-editor `internal/domain/data`](https://github.com/gfriloux/dragonsword-save-editor/tree/main/internal/domain/data)',
    '(itself datamined / scraped; names © HOUND13 / respective owners).',
    '',
    'No community editor business/source code was copied.',
    'Chinese (`zh`) currently falls back to English until a local StringData export fills it.',
    '',
    `Generated by \`scripts/convert-dragon-sword-catalog.mjs\` on ${new Date().toISOString().slice(0, 10)}.`,
    ''
  ].join('\n'),
  'utf8'
)
console.log('wrote SOURCE.md')
